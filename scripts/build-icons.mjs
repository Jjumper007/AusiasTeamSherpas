// Builds web/lib/icons.js from Lucide (ISC licence, https://lucide.dev), so the static site ships
// only the icons it uses. Add a name to ICONS and run: npm run icons
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ICONS = [
  // onboarding answers
  "user-round", "sprout", "message-square-text", "chart-column",
  "tree-palm", "house", "graduation-cap", "life-buoy", "credit-card", "shield", "pencil-line",
  "bird", "shield-check", "users-round", "earth",
  // interface
  "arrow-left", "x", "chevron-left", "chevron-right", "play", "pause", "check", "copy", "mountain-snow", "clipboard-list", "user-pen",
];

const dir = join("node_modules", "lucide-static", "icons");
const out = {};
for (const name of ICONS) {
  const svg = readFileSync(join(dir, `${name}.svg`), "utf8");
  out[name] = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\s+/g, " ").trim();
}

const body = `// Generated by scripts/build-icons.mjs from Lucide (ISC licence, https://lucide.dev). Do not edit by hand.
const PATHS = ${JSON.stringify(out, null, 2)};

/** Inline SVG icon in the current text colour. Decorative by default (aria-hidden). */
export function icon(name, { size = "1em", label = null, cls = "" } = {}) {
  const inner = PATHS[name];
  if (!inner) return "";
  const a11y = label ? \`role="img" aria-label="\${label}"\` : 'aria-hidden="true" focusable="false"';
  return \`<svg class="ic \${cls}" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" \${a11y}>\${inner}</svg>\`;
}
`;
writeFileSync(join("web", "lib", "icons.js"), body);
console.log(`web/lib/icons.js: ${ICONS.length} icons`);
